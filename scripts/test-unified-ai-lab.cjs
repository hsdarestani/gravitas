'use strict';
const fs = require('fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');

const html=fs.readFileSync('lab.html','utf8');
const integrations=fs.readFileSync('assets/public-integrations.js','utf8');
const chat=fs.readFileSync('assets/chat.js','utf8');
const brand=fs.readFileSync('brand.html','utf8');
const guidance=fs.readFileSync('CLAUDE.md','utf8');
new vm.Script(integrations,{filename:'assets/public-integrations.js'});
new vm.Script(chat,{filename:'assets/chat.js'});

assert.match(html, /<header class="g-header">/, 'shared navigation must remain');
assert.match(html, /<main id="main">/, 'main landmark missing');
assert.match(html, /<title>Lab · GraviQuest<\/title>/, 'generic page title missing');
assert.doesNotMatch(html, /<h1[^>]*>AI in Research<\/h1>/, 'Topic should not become Lab title');
assert.match(html, /<h1[^>]*id="lab-title"[^>]*>Change the conditions\. Watch what follows\.<\/h1>/, 'generic Lab title missing');
assert.match(html, /<p class="g-eyebrow">Lab &middot; Open to Every Topic<\/p>/, 'Lab must name itself, not a Topic');
assert.match(html, /class="g-hero lp-hero lab-hero/, 'must use the brand hero shared with the home and community pages');
assert.match(html, /assets\/hero\.css/, 'brand hero styles missing');
assert.match(html, /assets\/landing\.css/, 'landing chapters missing');
assert.match(html, /assets\/gravitas\.css/, 'brand design system missing');
assert.match(html, /assets\/site\.css/, 'site design system missing');
assert.match(html, /assets\/local-fonts\.css/, 'brand typography missing');
assert.match(html, /assets\/site\.js/, 'shared header behaviour missing');
assert.equal((html.match(/<h1\b/g)||[]).length,1,'only one visible heading');
assert.match(html, /<div id="lab-experiences" hidden aria-live="polite"><\/div>/, 'published Labs must come only from the registry');
assert.ok(!html.includes('<iframe'),'no experiment may be embedded in the static page');
assert.ok(!/data-lab-slug=/.test(html),'no Lab may be hard-coded into the landing');
assert.ok(!html.includes('ai-hero')&&!html.includes('ai-panel')&&!html.includes('ai-path-card'),'prototype content must be removed');
assert.ok(!html.includes('ai-lab.js')&&!html.includes('ai-lab.css'),'prototype assets must not be used');
assert.ok(!fs.existsSync('assets/ai-lab.js')&&!fs.existsSync('assets/ai-lab.css'),'discarded prototype assets must be removed');
assert.ok(!integrations.includes('games.prepend(a)'),'legacy CMS catalog must not be injected');
assert.match(chat, /lists only the models that have been published/,'site guide must be truthful');
assert.match(brand, /current centre of gravity is AI and machine learning in scientific research/);
assert.match(guidance, /canonical source of truth for all UI design is/,'future brand guidance missing');
console.log('Topic-agnostic Lab: generic landing, registry-only experiences, brand foundations and public messaging PASS.');
