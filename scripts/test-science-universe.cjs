'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..','lab-sources','science-universe');
const E=require(path.join(root,'engine.js'));
const config=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
const first=E.make(42);
assert.equal(first.labs.length,28,'exactly 28 seeded labs');
assert.ok(first.agents.length>=100,'at least 100 independently parameterised agents');
assert.equal(first.labs.filter(l=>l.domain===0).length,7,'each field has 7 labs');
assert.ok(first.links.length>=14,'network topology connects laboratories');
assert.equal(Object.keys(first.policy).length,12,'12 configurable policy dimensions');
assert.equal(E.make(42).rng,first.rng,'same seed creates same initial random state');
assert.deepEqual(E.make(42).labs,first.labs,'initial geometry is reproducible');
const twin=E.fork(first);
assert.deepEqual(twin,first,'fork is a deep exact checkpoint');
E.step(first,60);E.step(twin,60);
assert.deepEqual(twin,first,'unmodified deterministic forks never drift');
const summary=E.summary(first);
assert.ok(summary.generated>0,'agents generate testable hypotheses');
assert.ok(summary.tested>0,'hypotheses actually complete tests');
assert.equal(summary.tested,summary.rejected+first.queues.review.length+first.papers.length,
  'each tested hypothesis is rejected, queued or published');
assert.equal(summary.published,first.papers.length,'publications match state');
assert.equal(summary.falsePublished+summary.truePublished,summary.healthyPapers,
  'live truth partition matches non-retracted papers');
assert.ok(first.hypotheses.every(h=>typeof h.truth==='boolean'),'model tracks hidden ground truth');
assert.ok(first.history.length>=5,'time series comes from model snapshots');
const A=E.fork(first),B=E.fork(first);
E.editPolicy(B,'verification',10);E.editPolicy(B,'replication',9);
E.step(A,60);E.step(B,60);
assert.equal(A.day,B.day,'parallel worlds share the same time horizon');
assert.ok(A.stats.generated>0&&B.stats.generated>0);
assert.notDeepEqual(E.summary(A),E.summary(B),'different review rules can cause distinct outcomes');
assert.equal(first.policy.verification,5,'editing fork does not mutate ancestor');
const lab=first.labs[0];
const beforeBudget=lab.budget,beforePool=first.pool;
const funding=E.intervention(first,'fund',0,15);
assert.equal(funding.ok,true);
assert.ok(lab.budget>beforeBudget&&first.pool<beforePool,'funding transfers real credits');
const x=lab.x,y=lab.y;
assert.equal(E.intervention(first,'move',0,{x:x+.05,y:y+.05}).ok,true);
assert.notEqual(lab.x,x,'spatial reorganisation mutates geometry');
const method=lab.method;
E.intervention(first,'method',0);
assert.ok(lab.method>=method,'methods upgrade is applied');
E.intervention(first,'freeze',0);
assert.equal(lab.locked,true);
E.intervention(first,'freeze',0);
assert.equal(lab.locked,false);
const published=first.hypotheses.find(h=>h.published&&!h.retracted);
if(published){
  const check=E.intervention(first,'replicate_paper',published.labId,published.id);
  assert.ok(check.ok||check.error==='already_under_review','researcher can request independent replication');
}
assert.equal(E.editPolicy(first,'missing',4),false,'unregistered policies rejected');
assert.equal(E.editPolicy(first,'verification',100),true);
assert.equal(first.policy.verification,10,'policy bounds enforced');
assert.ok(!html.includes('cdn.jsdelivr.net')&&!html.includes('unpkg.com'),'offline local source assets only');
assert.match(html,/id="network-a"/);assert.match(html,/id="network-b"/);
assert.match(html,/id="inspector"/);assert.match(html,/id="comparison"/);
assert.match(html,/id="policy-controls"/);assert.match(html,/Model assumptions/);
assert.match(app,/G\.emit\(/,'Pulsar receives real model events');
assert.match(app,/E\.intervention/,'UI actions alter the engine');
assert.match(app,/E\.fork/,'comparison forks engine state');
assert.match(css,/max-width:520px/,'responsive fallback is authored');
const deploy=fs.readFileSync(path.join(__dirname,'..','.github','workflows','deploy.yml'),'utf8');
assert.match(deploy,/--exclude 'lab-sources\/'/,'draft sources must be hidden from Nginx public document root');
assert.match(deploy,/\/opt\/gravitas-backend\/lab-sources\/science-universe/,'draft sources must live in private backend storage');
assert.match(deploy,/install_science_universe_lab/,'draft import must be part of controlled deployment');
assert.equal(config.slug,'science-universe');
assert.deepEqual(config.config.components,['stage'],'no duplicate shell control panels');
assert.ok(config.config.sections.length>=6,'teaching path spans the experience');
for(const item of config.config.guidance)
 assert.ok(item.hint.length<300,'short authored Pulsar hints');
console.log('PASS Science Universe: seeded 28-lab ABM, 100+ agents, deterministic forks, scientific pipeline, real interventions, two worlds, Pulsar and mobile contracts.');
