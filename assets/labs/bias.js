/* Prompt framing Monte Carlo teaching simulation; deliberately NO live LLM calls. */
(function () {
  "use strict";
  const E=window.GraviLab,$=id=>document.getElementById(id);
  if(!E){document.body.textContent="The lab engine could not load.";return;}
  const fields=["agreeability","evidence","runs","seed"];
  let result=null;
  function input(){
    const value={};fields.forEach(id=>{value[id]=Number($(id).value);});return value;
  }
  function render(){
    result=E.bias(input());
    $("agreeabilityValue").textContent=Math.round(result.agreeability*100)+"%";
    $("evidenceValue").textContent=Math.round(result.evidence*100)+"%";
    $("runsValue").textContent=result.runs+" paired trials";
    $("seedValue").textContent=result.seed;
    $("neutralRate").textContent=Math.round(result.neutralRate*100)+"%";
    $("leadingRate").textContent=Math.round(result.leadingRate*100)+"%";
    $("gap").textContent=Math.round((result.leadingRate-result.neutralRate)*100)+" pts";
    $("neutralN").textContent=result.neutralAgree+" of "+result.runs;
    $("leadingN").textContent=result.leadingAgree+" of "+result.runs;
    $("neutralBar").style.width=(result.neutralRate*100).toFixed(1)+"%";
    $("leadingBar").style.width=(result.leadingRate*100).toFixed(1)+"%";
    $("readout").textContent="In this toy model, a leading question produced "+
      (result.leadingAgree-result.neutralAgree)+" more agreements with an unsupported claim across "+
      result.runs+" paired simulated trials. The rates are generated by an illustrative formula, not observations from Pulsar or any other AI.";
  }
  fields.forEach(id=>$(id).addEventListener("change",render));
  $("run").addEventListener("click",render);
  $("newSeed").addEventListener("click",()=>{
    const v=Number($("seed").value);$("seed").value=(Math.floor(v)%2147483600)+17;
    render();$("saved").textContent="New seed calculated. Experiment remains reproducible.";
  });
  $("reset").addEventListener("click",()=>{
    Object.entries({agreeability:75,evidence:65,runs:100,seed:4701}).forEach(([id,v])=>{$(id).value=v;});
    render();$("saved").textContent="Defaults restored.";
  });
  $("save").addEventListener("click",()=>{
    const row={kind:"toy-prompt-framing",version:E.version,createdAt:new Date().toISOString(),settings:input(),result};
    try{
      const key="gq-topic01-bias-runs",old=JSON.parse(localStorage.getItem(key)||"[]");
      const list=Array.isArray(old)?old.slice(-11):[];list.push(row);
      localStorage.setItem(key,JSON.stringify(list));
      $("saved").textContent="Run saved locally ("+list.length+" total). No server or AI API request was made.";
    }catch(_){$("saved").textContent="Local storage unavailable. Export is still possible.";}
  });
  $("export").addEventListener("click",()=>{
    const payload={method:"Synthetic Monte Carlo educational model, not an LLM evaluation",engine:E.version,settings:input(),result};
    const blob=new Blob([JSON.stringify(payload,null,2)],{type:"application/json"});
    const url=URL.createObjectURL(blob),link=document.createElement("a");
    link.href=url;link.download="graviquest-prompt-bias-run.json";link.click();
    setTimeout(()=>URL.revokeObjectURL(url),1000);
  });
  render();
})();
